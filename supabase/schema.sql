-- ==========================================
-- SECURE EXAM WRAPPER (MVP DATABASE SCHEMA)
-- ==========================================

-- 1. Enable pgcrypto for UUIDs & hashing if needed
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 2. ORGANIZERS TABLE (Linked with auth.users)
CREATE TABLE IF NOT EXISTS public.organizers (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    full_name TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. EXAMS TABLE
CREATE TABLE IF NOT EXISTS public.exams (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    organizer_id UUID NOT NULL REFERENCES public.organizers(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    form_url TEXT NOT NULL,
    code TEXT NOT NULL UNIQUE, -- 6-8 chars (e.g. MAT101)
    token_hash TEXT NOT NULL,  -- hashed default exam token
    opens_at TIMESTAMPTZ NOT NULL,
    closes_at TIMESTAMPTZ NOT NULL,
    duration_min INTEGER NOT NULL DEFAULT 60,
    tolerance INTEGER NOT NULL DEFAULT 1, -- violations before locked
    wm_opacity NUMERIC(3,2) NOT NULL DEFAULT 0.15, -- 0.05 to 0.50
    status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'scheduled', 'ongoing', 'finished')),
    max_participants INTEGER NOT NULL DEFAULT 200,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Index for participant lookups
CREATE INDEX IF NOT EXISTS idx_exams_code ON public.exams(code);
CREATE INDEX IF NOT EXISTS idx_exams_organizer_id ON public.exams(organizer_id);

-- 4. PARTICIPANTS TABLE
CREATE TABLE IF NOT EXISTS public.participants (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    exam_id UUID NOT NULL REFERENCES public.exams(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    ref_id TEXT, -- e.g. NISN, Student ID, or Class
    individual_token_hash TEXT, -- optional individual token
    device_id TEXT, -- locked device identifier (random UUID stored in localStorage)
    user_agent_summary TEXT,
    locked_name BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(exam_id, name)
);

CREATE INDEX IF NOT EXISTS idx_participants_exam_id ON public.participants(exam_id);

-- 5. SESSIONS TABLE
CREATE TABLE IF NOT EXISTS public.sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    participant_id UUID NOT NULL REFERENCES public.participants(id) ON DELETE CASCADE,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ends_at TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress', 'submitted', 'abandoned')),
    violation_count INTEGER NOT NULL DEFAULT 0,
    is_locked BOOLEAN NOT NULL DEFAULT FALSE,
    last_heartbeat_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    no_fullscreen BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(participant_id)
);

CREATE INDEX IF NOT EXISTS idx_sessions_participant_id ON public.sessions(participant_id);

-- 6. EVENTS TABLE (Audit Log)
CREATE TABLE IF NOT EXISTS public.events (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES public.sessions(id) ON DELETE CASCADE,
    type TEXT NOT NULL, -- 'start', 'tab_switch', 'fullscreen_exit', 'copy_attempt', 'tamper_watermark', 'lock', 'unlock', 'heartbeat_lost', 'submit'
    meta JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_events_session_id ON public.events(session_id);

-- 7. UNLOCK REQUESTS TABLE
CREATE TABLE IF NOT EXISTS public.unlock_requests (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id UUID NOT NULL REFERENCES public.sessions(id) ON DELETE CASCADE,
    lock_id VARCHAR(6) NOT NULL, -- 6 digit human readable code
    code_hash TEXT NOT NULL,     -- hashed one-time unlock code generated by supervisor
    expires_at TIMESTAMPTZ NOT NULL,
    is_used BOOLEAN NOT NULL DEFAULT FALSE,
    used_at TIMESTAMPTZ,
    used_by UUID REFERENCES auth.users(id),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_unlock_requests_lock_id ON public.unlock_requests(lock_id);

-- 8. SUPERVISORS TABLE
CREATE TABLE IF NOT EXISTS public.supervisors (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    exam_id UUID NOT NULL REFERENCES public.exams(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(exam_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_supervisors_user_id ON public.supervisors(user_id);

-- ==========================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- ==========================================

ALTER TABLE public.organizers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exams ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.unlock_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.supervisors ENABLE ROW LEVEL SECURITY;

-- ORGANIZERS: user can only view & update their own record
CREATE POLICY "Users can manage own organizer profile"
ON public.organizers FOR ALL
USING (auth.uid() = id);

-- EXAMS:
-- Organizer has full control of own exams
CREATE POLICY "Organizers manage their exams"
ON public.exams FOR ALL
USING (auth.uid() = organizer_id);

-- Supervisors can read exams they supervise
CREATE POLICY "Supervisors can view assigned exams"
ON public.exams FOR SELECT
USING (
    EXISTS (
        SELECT 1 FROM public.supervisors
        WHERE supervisors.exam_id = exams.id AND supervisors.user_id = auth.uid()
    )
);

-- Anonymous / Participants can view public exam metadata (status, code, title, duration) to join
CREATE POLICY "Public can view basic exam info by code"
ON public.exams FOR SELECT
TO anon
USING (status IN ('scheduled', 'ongoing', 'draft'));

-- PARTICIPANTS:
-- Organizers and Supervisors can read/write participants of their exams
CREATE POLICY "Organizers and supervisors view participants"
ON public.participants FOR ALL
USING (
    EXISTS (
        SELECT 1 FROM public.exams
        WHERE exams.id = participants.exam_id
          AND (exams.organizer_id = auth.uid() OR EXISTS (
              SELECT 1 FROM public.supervisors WHERE supervisors.exam_id = exams.id AND supervisors.user_id = auth.uid()
          ))
    )
);

-- Anonymous participants can view available participants for joining (where locked_name = false or same device)
CREATE POLICY "Public can view unlocked participants for exam"
ON public.participants FOR SELECT
TO anon
USING (true);

CREATE POLICY "Public can update participant to lock device"
ON public.participants FOR UPDATE
TO anon
USING (true);

-- SESSIONS:
-- Organizers and Supervisors can view sessions
CREATE POLICY "Organizers and supervisors view sessions"
ON public.sessions FOR ALL
USING (
    EXISTS (
        SELECT 1 FROM public.participants
        JOIN public.exams ON exams.id = participants.exam_id
        WHERE participants.id = sessions.participant_id
          AND (exams.organizer_id = auth.uid() OR EXISTS (
              SELECT 1 FROM public.supervisors WHERE supervisors.exam_id = exams.id AND supervisors.user_id = auth.uid()
          ))
    )
);

-- Public / Anonymous can read and manage their active session
CREATE POLICY "Public can manage session"
ON public.sessions FOR ALL
TO anon
USING (true);

-- EVENTS:
CREATE POLICY "Organizers and supervisors view events"
ON public.events FOR SELECT
USING (
    EXISTS (
        SELECT 1 FROM public.sessions
        JOIN public.participants ON participants.id = sessions.participant_id
        JOIN public.exams ON exams.id = participants.exam_id
        WHERE sessions.id = events.session_id
          AND (exams.organizer_id = auth.uid() OR EXISTS (
              SELECT 1 FROM public.supervisors WHERE supervisors.exam_id = exams.id AND supervisors.user_id = auth.uid()
          ))
    )
);

CREATE POLICY "Public can insert audit events"
ON public.events FOR INSERT
TO anon
WITH CHECK (true);

-- UNLOCK REQUESTS:
CREATE POLICY "Organizers and supervisors manage unlock requests"
ON public.unlock_requests FOR ALL
USING (
    EXISTS (
        SELECT 1 FROM public.sessions
        JOIN public.participants ON participants.id = sessions.participant_id
        JOIN public.exams ON exams.id = participants.exam_id
        WHERE sessions.id = unlock_requests.session_id
          AND (exams.organizer_id = auth.uid() OR EXISTS (
              SELECT 1 FROM public.supervisors WHERE supervisors.exam_id = exams.id AND supervisors.user_id = auth.uid()
          ))
    )
);

CREATE POLICY "Public can create and view own unlock request"
ON public.unlock_requests FOR ALL
TO anon
USING (true);

-- SUPERVISORS:
CREATE POLICY "Organizers manage supervisors"
ON public.supervisors FOR ALL
USING (
    EXISTS (
        SELECT 1 FROM public.exams
        WHERE exams.id = supervisors.exam_id AND exams.organizer_id = auth.uid()
    )
);

CREATE POLICY "Supervisors view their invitations"
ON public.supervisors FOR SELECT
USING (user_id = auth.uid());

-- Trigger to create organizer record on auth.users sign up
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.organizers (id, email, full_name)
    VALUES (NEW.id, NEW.email, NEW.raw_user_meta_data->>'full_name')
    ON CONFLICT (id) DO NOTHING;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

